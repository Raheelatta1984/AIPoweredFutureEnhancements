/**
 * Bakes db/migrations/*.sql into db/migrations.generated.ts so runtime code never
 * needs filesystem access to .sql files (important for serverless bundles).
 * Runs as predev / prebuild.
 */
import { mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, "..");
const migrationsDir = join(root, "db", "migrations");
const outFile = join(root, "db", "migrations.generated.ts");

const files = readdirSync(migrationsDir)
  .filter((f) => f.endsWith(".sql"))
  .sort();

const entries = files.map((file) => {
  const sql = readFileSync(join(migrationsDir, file), "utf8");
  return { id: file.replace(/\.sql$/, ""), sql };
});

const body = entries
  .map(
    (e) =>
      `  {\n    id: ${JSON.stringify(e.id)},\n    sql: ${JSON.stringify(e.sql)},\n  },`,
  )
  .join("\n");

const contents = `// AUTO-GENERATED by scripts/embed-migrations.mjs — do not edit by hand.
export type EmbeddedMigration = { id: string; sql: string };

export const MIGRATIONS: EmbeddedMigration[] = [
${body}
];
`;

mkdirSync(dirname(outFile), { recursive: true });
writeFileSync(outFile, contents, "utf8");
console.log(
  `[db:embed] wrote ${entries.length} migration(s) to db/migrations.generated.ts`,
);
